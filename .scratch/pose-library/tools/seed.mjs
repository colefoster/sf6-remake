/** 2MK writes a whole number as `0.0`, not `0`. */
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const pt = ([x, y]) => `{ "x": ${num(x)}, "y": ${num(y)} }`;
const pair = (a, i) => `[\n${i}  ${pt(a[0])},\n${i}  ${pt(a[1])}\n${i}]`;

const poseText = (pose, i) =>
  [
    `{`,
    `${i}  "pelvis": ${pt(pose.pelvis)},`,
    `${i}  "chest": ${pt(pose.chest)},`,
    `${i}  "head": ${pt(pose.head)},`,
    `${i}  "hands": ${pair(pose.hands, `${i}  `)},`,
    `${i}  "feet": ${pair(pose.feet, `${i}  `)}`,
    `${i}}`,
  ].join("\n");

mkdirSync(OUT, { recursive: true });
for (const [move, spec] of Object.entries(MOVES)) {
  const keys = spec.keys
    .map(
      ([at, pose]) =>
        `    {\n      "at": ${Array.isArray(at) ? `["${at[0]}", ${at[1]}]` : JSON.stringify(at)},\n      "pose": ${poseText(pose, "      ")}\n    }`,
    )
    .join(",\n");
  const text = [
    `{`,
    `  "character": "ryu",`,
    `  "move": ${JSON.stringify(move)},`,
    `  "action": ${JSON.stringify(spec.action)},`,
    `  "keys": [`,
    keys,
    `  ]`,
    `}`,
    ``,
  ].join("\n");
  writeFileSync(join(OUT, `${move}.json`), text);
  console.log(`wrote ${move}.json  ${spec.keys.length} keys`);
}
